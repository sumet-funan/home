export interface CameraView {
  pos: V3;
  target: V3;
}

const flat0: FramePose = { kind: 'flat', stack: 0 };
const onSlab = (local: V3): V3 => {
  const v = new Vector3(...local).applyMatrix4(frameMatrix(1, flat0));
  return [v.x, v.y, v.z];
};
const offset = (t: V3, d: V3): CameraView => ({ target: t, pos: [t[0] + d[0], t[1] + d[1], t[2] + d[2]] });

