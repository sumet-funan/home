// ─────────────────────────── สถานะสะสม ───────────────────────────
export interface SceneState {
  visible: Set<string>;
  poses: Record<number, FramePose>;
}

/** สถานะฉากหลังทำขั้นที่ index เสร็จ (−1 = ก่อนเริ่ม) */
export function stateAt(index: number): SceneState {
  const visible = new Set<string>();
  const poses: Record<number, FramePose> = {};
  for (let i = 0; i <= index && i < STEPS.length; i++) {
    const s = STEPS[i];
    s.remove?.forEach((t) => visible.delete(t));
    s.add?.forEach((t) => visible.add(t));
    if (s.pose) Object.assign(poses, s.pose);
  }
  return { visible, poses };
}

/** สถานะหลังเสร็จทุกขั้น + กล่องโฟม (หน้าสรุป) */
export function finalState(): SceneState {
  const s = stateAt(STEPS.length - 1);
  s.visible.add('foam-boxes');
  return s;
}

export const stepIndexById = (id: string) => STEPS.findIndex((s) => s.id === id);
